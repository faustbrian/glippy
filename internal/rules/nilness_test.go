func TestNilnessReportsOnlyProvenSSAFindings(t *testing.T) {
	t.Parallel()

	root, path := writeNilnessModule(
		t,
		`package sample

func inspect(pointer *int, values []int) {
	if pointer == nil {
		_ = *pointer
	}
	if pointer != nil {
		_ = *pointer
	}
	if values == nil {
		_ = (*[1]int)(values)
	}
}

func impossible() {
	channel := make(chan int)
	if channel == nil { println(channel) }
}

func nilPanic() { panic(nil) }

func unknown(pointer *int) { _ = *pointer }
`,
	)
	registry, err := rules.NewDefaultRegistry()
	if err != nil {
		t.Fatal(err)
	}

	result, err := analysis.RunPackages(
		context.Background(),
		registry,
		analysis.RunOptions{Preset: rules.PresetSuspicious},
		analysis.PackageLoadOptions{Dir: root, Patterns: []string{"."}},
	)
	if err != nil {
		t.Fatal(err)
	}
	if len(result.Files) != 1 || result.Files[0].Path != path {
		t.Fatalf("RunPackages() files = %#v", result.Files)
	}

	got := make([]string, len(result.Files[0].Diagnostics))
	file, found := result.Sources.Lookup(path)
	if !found {
		t.Fatalf("RunPackages() did not retain %q", path)
	}
	for index, diagnostic := range result.Files[0].Diagnostics {
		text, valid := file.Slice(diagnostic.Range)
		if !valid || text == "" {
			t.Fatalf(
				"diagnostic %d range = %#v, text = %q, valid = %v",
				index,
				diagnostic.Range,
				text,
				valid,
			)
		}
		if diagnostic.RuleID != "nilness" ||
			diagnostic.Severity != rules.SeverityWarn ||
			len(diagnostic.Fixes) != 0 {
			t.Fatalf("diagnostic %d = %#v", index, diagnostic)
		}
		got[index] = diagnostic.MessageKey + ":" + text
	}
	want := []string{"nilderef:*", "conversionpanic:(", "cond:==", "nilpanic:("}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("nilness diagnostics = %#v, want %#v", got, want)
	}
}

func TestNilnessHonorsSuppressionGeneratedAndTypeErrorPolicies(t *testing.T) {
	t.Parallel()

	root, path := writeNilnessModule(
		t,
		`// Code generated by fixture. DO NOT EDIT.
package sample

func generated(pointer *int) {
	if pointer == nil {
		_ = *pointer
	}
}
`,
	)
	registry, err := rules.NewDefaultRegistry()
	if err != nil {
		t.Fatal(err)
	}
	result, err := analysis.RunPackages(
		context.Background(),
		registry,
		analysis.RunOptions{Preset: rules.PresetSuspicious},
		analysis.PackageLoadOptions{Dir: root, Patterns: []string{"."}},
	)
	if err != nil {
		t.Fatal(err)
	}
	if len(result.Files) != 1 ||
		result.Files[0].Path != path ||
		len(result.Files[0].Diagnostics) != 0 ||
		len(result.Files[0].Suppressed) != 0 ||
		len(result.Files[0].UnusedSuppressions) != 0 ||
		len(result.Files[0].SuppressionProblems) != 0 {
		t.Fatalf("generated result = %#v", result)
	}

	brokenRoot, _ := writeNilnessModule(
		t,
		`package sample
func broken(pointer *missing) { _ = *pointer }
`,
	)
	broken, err := analysis.RunPackages(
		context.Background(),
		registry,
		analysis.RunOptions{Preset: rules.PresetSuspicious},
		analysis.PackageLoadOptions{Dir: brokenRoot, Patterns: []string{"."}},
	)
	if err != nil {
		t.Fatal(err)
	}
	if len(broken.LoadDiagnostics) == 0 ||
		len(broken.Files) != 1 ||
		len(broken.Files[0].Diagnostics) != 0 {
		t.Fatalf("type-error result = %#v", broken)
	}
}

func TestNilnessSuppressionsAndSeverityUseCanonicalRuleIdentity(t *testing.T) {
	t.Parallel()

	root, _ := writeNilnessModule(
		t,
		`package sample
func inspect(pointer *int) {
	if pointer == nil {
		//gox:ignore nilness -- guarded for a proving fixture
		_ = *pointer
	}
}
`,
	)
	registry, err := rules.NewDefaultRegistry()
	if err != nil {
		t.Fatal(err)
	}
	result, err := analysis.RunPackages(
		context.Background(),
		registry,
		analysis.RunOptions{
			Preset: rules.PresetSuspicious,
			Overrides: map[string]rules.Severity{"nilness": rules.SeverityError},
		},
		analysis.PackageLoadOptions{Dir: root, Patterns: []string{"."}},
	)
	if err != nil {
		t.Fatal(err)
	}
	if len(result.Files) != 1 ||
		len(result.Files[0].Diagnostics) != 0 ||
		len(result.Files[0].Suppressed) != 1 ||
		result.Files[0].Suppressed[0].Diagnostic.RuleID != "nilness" ||
		result.Files[0].Suppressed[0].Diagnostic.Severity != rules.SeverityError ||
		len(result.Files[0].UnusedSuppressions) != 0 ||
		len(result.Files[0].SuppressionProblems) != 0 {
		t.Fatalf("suppressed result = %#v", result.Files)
	}
}

