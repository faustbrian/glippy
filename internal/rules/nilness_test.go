func TestNilnessReportsOnlyProvenSSAFindings(t *testing.T) {
	t.Parallel()

	root, path := writeNilnessModule(
		t,
		`package sample

func inspect(pointer *int, values []int) {
	if pointer == nil {
		_ = *pointer
	}
	if pointer != nil {
		_ = *pointer
	}
	if values == nil {
		_ = (*[1]int)(values)
	}
}

func impossible() {
	channel := make(chan int)
	if channel == nil { println(channel) }
}

func nilPanic() { panic(nil) }

func unknown(pointer *int) { _ = *pointer }
`,
	)
	registry, err := rules.NewDefaultRegistry()
	if err != nil {
		t.Fatal(err)
	}

	result, err := analysis.RunPackages(
		context.Background(),
		registry,
		analysis.RunOptions{Preset: rules.PresetSuspicious},
		analysis.PackageLoadOptions{Dir: root, Patterns: []string{"."}},
	)
	if err != nil {
		t.Fatal(err)
	}
	if len(result.Files) != 1 || result.Files[0].Path != path {
		t.Fatalf("RunPackages() files = %#v", result.Files)
	}

	got := make([]string, len(result.Files[0].Diagnostics))
	file, found := result.Sources.Lookup(path)
	if !found {
		t.Fatalf("RunPackages() did not retain %q", path)
	}
	for index, diagnostic := range result.Files[0].Diagnostics {
		text, valid := file.Slice(diagnostic.Range)
		if !valid || text == "" {
			t.Fatalf(
				"diagnostic %d range = %#v, text = %q, valid = %v",
				index,
				diagnostic.Range,
				text,
				valid,
			)
		}
		if diagnostic.RuleID != "nilness" ||
			diagnostic.Severity != rules.SeverityWarn ||
			len(diagnostic.Fixes) != 0 {
			t.Fatalf("diagnostic %d = %#v", index, diagnostic)
		}
		got[index] = diagnostic.MessageKey + ":" + text
	}
	want := []string{"nilderef:*", "conversionpanic:(", "cond:==", "nilpanic:("}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("nilness diagnostics = %#v, want %#v", got, want)
	}
}

