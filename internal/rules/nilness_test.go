func TestTypesControlFlowAndSSARulesRemainOptIn(t *testing.T) {
	t.Parallel()

	registry, err := rules.NewDefaultRegistry()
	if err != nil {
		t.Fatal(err)
	}
	correctness, err := registry.Resolve(rules.PresetCorrectness, nil)
	if err != nil {
		t.Fatal(err)
	}
	if len(correctness) != 2 ||
		correctness[0].ID != "duplicate-condition" ||
		correctness[1].ID != "ineffective-break" {
		t.Fatalf("correctness selection = %#v", correctness)
	}
	suspicious, err := registry.Resolve(rules.PresetSuspicious, nil)
	if err != nil {
		t.Fatal(err)
	}
	if len(suspicious) != 4 ||
		suspicious[0].ID != "context-key" ||
		suspicious[0].Requirement != rules.RequireTypes ||
		suspicious[1].ID != "defer-in-infinite-loop" ||
		suspicious[1].Requirement != rules.RequireControlFlow ||
		suspicious[2].ID != "errors-is-arguments" ||
		suspicious[2].Requirement != rules.RequireTypes ||
		suspicious[3].ID != "nilness" ||
		suspicious[3].Requirement != rules.RequireSSA {
		t.Fatalf("suspicious selection = %#v", suspicious)
	}
}

func BenchmarkNilnessSharedSSA(b *testing.B) {
	root := b.TempDir()
	if err := os.WriteFile(
		filepath.Join(root, "go.mod"),
		[]byte("module example.com/nilness\n\ngo 1.26.0\n"),
		0o600,
	);
		err != nil {
		b.Fatal(err)
	}
	var input strings.Builder
	input.WriteString("package sample\n")
	for index := range 100 {
		fmt.Fprintf(
			&input,
			"func inspect%d(pointer *int) { if pointer == nil { _ = *pointer } }\n",
			index,
		)
	}
	if err := os.WriteFile(filepath.Join(root, "sample.go"), []byte(input.String()), 0o600);
		err != nil {
		b.Fatal(err)
	}
	loaded, err := analysis.LoadPackages(
		context.Background(),
		analysis.PackageLoadOptions{
			Dir: root,
			Patterns: []string{"."},
			Requirement: rules.RequireSSA,
		},
	)
	if err != nil {
		b.Fatal(err)
	}
	nilnessRegistry, err := rules.NewDefaultRegistry()
	if err != nil {
		b.Fatal(err)
	}
	nilnessSelection, err := nilnessRegistry.Resolve(
		rules.PresetSuspicious,
		map[string]rules.Severity{
			"context-key": rules.SeverityOff,
			"defer-in-infinite-loop": rules.SeverityOff,
			"errors-is-arguments": rules.SeverityOff,
		},
	)
	if err != nil {
		b.Fatal(err)
	}
	baselineRegistry, err := rules.NewRegistry(benchmarkSSARule{})
	if err != nil {
		b.Fatal(err)
	}
	baselineSelection, err := baselineRegistry.Resolve(rules.PresetSuspicious, nil)
	if err != nil {
		b.Fatal(err)
	}

	b.Run(
		"baseline",
		func(b *testing.B) {
			benchmarkSSAExecution(b, loaded, baselineRegistry, baselineSelection, 0)
		},
	)
	b.Run(
		"nilness",
		func(b *testing.B) {
			benchmarkSSAExecution(b, loaded, nilnessRegistry, nilnessSelection, 100)
		},
	)
}

func benchmarkSSAExecution(
	b *testing.B,
	loaded analysis.PackageLoadResult,
	registry *rules.Registry,
	selection []rules.Selection,
	wantDiagnostics int,
) {
	b.Helper()
	b.ReportAllocs()
	for range b.N {
		diagnostics, err := analysis.RunSSA(
			context.Background(),
			loaded,
			registry,
			selection,
		)
		if err != nil {
			b.Fatal(err)
		}
		if len(diagnostics) != wantDiagnostics {
			b.Fatalf("diagnostics = %d, want %d", len(diagnostics), wantDiagnostics)
		}
	}
}

func writeNilnessModule(t *testing.T, source string) (string, string) {
	t.Helper()
	root := t.TempDir()
	if err := os.WriteFile(
		filepath.Join(root, "go.mod"),
		[]byte("module example.com/nilness\n\ngo 1.26.0\n"),
		0o600,
	);
		err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(root, "sample.go")
	if err := os.WriteFile(path, []byte(source), 0o600); err != nil {
		t.Fatal(err)
	}
	return root, path
}
